-- 0017：任务的播放列表条目数上限（2026-11-01）。
--
-- playlist_items：合集/频道/播放列表类链接要下多少条。0 = 全部（默认）。
--
-- 为什么需要：解析预览用 --playlist-items 1 只解析第一条（快），但**下载阶段
-- 会把整个列表都拉下来**——用户预览时看到的是第一条的标题与清晰度，
-- 以为只下一个，点下去却开始下 25 个 1080P（几十 GB）。
--
-- 引擎侧对应 yt-dlp 的 --playlist-items N：给定时只取前 N 条。
-- 0 表示不限（沿用既有行为）。
--
-- 与 exit_used 同属「把隐式行为显式化」：配置项与字段都让用户能看见、能选择。
ALTER TABLE tasks ADD COLUMN playlist_items INTEGER NOT NULL DEFAULT 0;
