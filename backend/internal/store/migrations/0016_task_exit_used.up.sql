-- 0016：任务本轮**实际使用的出口**（2026-10-30）。
--
-- exit_used：最近一轮真正走的出口（代理地址；空串=直连）。
--
-- 为什么要有这一列（与已有的 proxy 列分开）：
--
--   proxy    = **用户配置的代理**（tasks.proxy）——「这个任务该走哪条出口」的设定
--   exit_used= **本轮实际使用的出口**——「这一轮事实上走了哪条出口」的记录
--
-- 此前两者被混为一谈：重试分支只看 tasks.proxy 有没有值，就断言「已自动切换代理」。
-- 但出口决策是「显式 > 任务级 > 全局 net.proxy > 直连」——
-- 任务没配 proxy 时，**全局 net.proxy 本来就在用**，于是：
--
--   · 所谓的「切换」把 proxy 字段写成同一个全局代理 = 出口根本没变；
--   · 日志却打印「已自动切换代理」——**误导排障**（用户会以为出口变了，
--     去查错方向，比如怀疑代理规则没覆盖、其实问题在别处）。
--
-- 分开记录后，「配置」与「实况」各归各位：重试决策看 exit_used（事实），
-- 界面与事件流也能如实告诉用户这一轮走的是直连还是代理。
--
-- 空串 = 直连（与 proxy 列同约定：空 = 不走代理）。
ALTER TABLE tasks ADD COLUMN exit_used TEXT NOT NULL DEFAULT '';
