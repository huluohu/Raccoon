package task

// credential.go：凭据中心 → 引擎入参的桥接（docs/01 §3.1「Cookie 过期 → 去连接页更新」）。
//
// 为什么需要这一层：凭据在 credentials 表里是 AES-256-GCM 密文，引擎（yt-dlp / gallery-dl）
// 需要的是「Cookie 文件路径」或「Cookie 头字符串」。这个文件负责：
//  1. 按平台取该平台的凭据（多个则取最近更新的一条）；
//  2. 解密；
//  3. 落成临时 Netscape cookie 文件供 yt-dlp / gallery-dl --cookies 使用；
//  4. 任务结束清理临时文件（凭据明文不落盘到数据目录之外的长期位置）。
//
// 安全约束：临时文件权限 0600，路径在数据根的 tmp 子目录下，任务结束即删。

import (
	"context"
	"os"
	"path/filepath"
	"strconv"
	"strings"
	"time"

	"github.com/huluohu/raccoon/internal/store"
)

// CredentialResolver 按平台取凭据明文。
//
// 接口化而非直连 store：task 包不应依赖具体存储实现细节，
// 也便于测试时注入假实现（单测里能构造「凭据过期」场景）。
type CredentialResolver interface {
	// PlatformCredential 返回该平台最近更新的一条凭据明文；没有则返回 ("", nil)。
	PlatformCredential(ctx context.Context, platform string) (string, error)
}

// CookieResolver 是 CredentialResolver 的实现：走 store + vault。
type CookieResolver struct {
	st    *store.Store
	vault VaultLike
}

// VaultLike 是凭据解密能力的最小接口（避免 task 包依赖 credential 包的实现细节）。
type VaultLike interface {
	Decrypt(cipherText []byte) ([]byte, error)
}

// NewCookieResolver 构造。
func NewCookieResolver(st *store.Store, vault VaultLike) *CookieResolver {
	return &CookieResolver{st: st, vault: vault}
}

// PlatformCredential 取平台凭据明文。
//
// 选取规则：同平台下优先 status='active'，其次最近 updated_at。
// 状态为 disabled/expired 的不取 —— 拿了也是失败，不如让引擎直接报「需登录」。
func (c *CookieResolver) PlatformCredential(ctx context.Context, platform string) (string, error) {
	if c == nil || c.st == nil || c.vault == nil || platform == "" {
		return "", nil
	}
	creds, err := c.st.ListCredentials()
	if err != nil {
		return "", err
	}
	var best *store.Credential
	for _, cr := range creds {
		if cr.Platform != platform {
			continue
		}
		if cr.Status == "disabled" || cr.Status == "expired" {
			continue
		}
		if best == nil || cr.UpdatedAt > best.UpdatedAt {
			best = cr
		}
	}
	if best == nil {
		return "", nil
	}
	_, cipher, err := c.st.GetCredential(best.ID)
	if err != nil {
		return "", err
	}
	if len(cipher) == 0 {
		return "", nil
	}
	plain, err := c.vault.Decrypt(cipher)
	if err != nil {
		return "", err
	}
	return string(plain), nil
}

// cookieFileWriter 负责把 Cookie 字符串落成临时文件。
type cookieFileWriter struct {
	dir string
}

// writeCookieFile 把 Cookie 头字符串写成 Netscape 格式 cookie 文件。
//
// Netscape 格式是 yt-dlp / gallery-dl 的 --cookies 唯一接受的形式：
//
//	domain	includeSubdomains	path	secure	expires	value
//
// 解析：把 "SESSDATA=xxx; bili_jct=yyy" 按 ";" 切成键值对，
// 域名从 Cookie 字符串里取（形如 "domain=.bilibili.com" 或用平台默认域名兜底）。
func (w cookieFileWriter) writeCookieFile(platform, cookieStr string) (string, error) {
	if strings.TrimSpace(cookieStr) == "" {
		return "", nil
	}
	if err := os.MkdirAll(w.dir, 0o700); err != nil {
		return "", err
	}
	domain := cookieDomainFor(platform)
	expires := time.Now().Add(30 * 24 * time.Hour).Unix()
	var sb strings.Builder
	sb.WriteString("# Netscape HTTP Cookie File\n")
	sb.WriteString("# Generated by Raccoon (temporary)\n")
	records := 0
	for _, pair := range strings.Split(cookieStr, ";") {
		pair = strings.TrimSpace(pair)
		if pair == "" {
			continue
		}
		kv := strings.SplitN(pair, "=", 2)
		if len(kv) != 2 {
			continue
		}
		name := strings.TrimSpace(kv[0])
		value := strings.TrimSpace(kv[1])
		if name == "" {
			continue
		}
		// 去掉可能的 domain= 前缀：用户常把整条 Cookie 头粘进来（含 domain 属性）。
		// 前导点必须保留 —— Netscape 格式里 ".example.com" 才匹配子域，
		// yt-dlp 对无点域名只做精确主机匹配（早先剥点导致子站登录态静默丢失）。
		if name == "domain" && value != "" {
			if !strings.HasPrefix(value, ".") {
				value = "." + value
			}
			domain = value
			continue
		}
		records++
		sb.WriteString(domain)
		sb.WriteString("\tTRUE\t/\tFALSE\t")
		sb.WriteString(strconv.FormatInt(expires, 10))
		sb.WriteString("\t")
		sb.WriteString(name)
		sb.WriteString("\t")
		sb.WriteString(value)
		sb.WriteString("\n")
	}
	// 一条有效记录都没解析出来（如用户只粘了 ";;;"）→ 不产文件，
	// 返回空串让上层走「无凭据」分支。空 cookie 文件对引擎是无意义产物。
	// 域名为空（平台未收录且用户没带 domain= 属性）同样不产文件：
	// 无域的 Netscape 记录无法安全限定发送范围，宁可不带凭据。
	if records == 0 || domain == "" {
		return "", nil
	}
	path := filepath.Join(w.dir, "cookie-"+platform+"-"+strconv.FormatInt(time.Now().UnixNano(), 10)+".txt")
	if err := os.WriteFile(path, []byte(sb.String()), 0o600); err != nil {
		return "", err
	}
	return path, nil
}

// removeCookieFile 清理临时 cookie 文件（任务结束调用；不存在不报错）。
func (w cookieFileWriter) removeCookieFile(path string) {
	if path == "" {
		return
	}
	_ = os.Remove(path)
}

// cookieDomainFor 平台默认 Cookie 域（用户未提供 domain 属性时用）。
//
// 未收录平台返回空串：宁可不带凭据（引擎照常跑、命中会员内容时如实报
// AUTH_REQUIRED），也不能像早先那样兜底 ".com" —— Netscape 域 ".com" 会让
// yt-dlp 把这枚凭据发给任何 .com 站点，等于把 B 站 Cookie 洒向全网。
// 未收录平台想用 Cookie：在凭据串里自带 "domain=.example.com" 属性即可。
func cookieDomainFor(platform string) string {
	switch platform {
	case "bilibili":
		return ".bilibili.com"
	case "xiaohongshu":
		return ".xiaohongshu.com"
	case "netease":
		return ".music.163.com"
	case "youtube":
		return ".youtube.com"
	case "douyin":
		return ".douyin.com"
	case "tiktok":
		return ".tiktok.com"
	case "weibo":
		return ".weibo.com"
	case "zhihu":
		return ".zhihu.com"
	case "twitter":
		return ".twitter.com"
	case "instagram":
		return ".instagram.com"
	case "youku":
		return ".youku.com"
	case "tencent":
		return ".v.qq.com"
	case "iqiyi":
		return ".iqiyi.com"
	case "pornhub":
		return ".pornhub.com"
	case "vimeo":
		return ".vimeo.com"
	case "soundcloud":
		return ".soundcloud.com"
	case "wechat", "wechat_channels", "yuanbao":
		return ".yuanbao.tencent.com"
	}
	return ""
}
